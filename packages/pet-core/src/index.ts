/**
 * # @pet/core — 공용 어휘
 *
 * 다섯 feature가 서로를 직접 의존하지 않으려면, 서로가 알아야 할 최소한의 어휘를 담는
 * 중립 지점이 필요하다. 그게 이 패키지다.
 *
 * ## 여기 있는 것과 없는 것
 *
 * 기준은 하나다 — **이견이 나면 설계 논쟁이 되는 것은 여기 두지 않는다.**
 *
 * | 있다 | 이유 |
 * |---|---|
 * | `PetId`, `Rarity`, `Coin`, `LocalDate`, `LocalMinute` | 펫 id는 누가 봐도 펫 id다. 이견이 날 여지가 작고, 틀려도 고치는 비용이 싸다 |
 * | `Clock` | 시간을 주입받는다는 것 자체는 논쟁거리가 아니다 |
 *
 * 이벤트 봉투, 이벤트 버스, 오류 표현, 도메인 간 포트는 **여기 없다.** 전부 "어떻게
 * 할지"가 아직 정해지지 않은 설계 결정이라, 각 feature가 자기 패키지 안에 자기 답을
 * 갖고 있다. 다음 주에 그 답들을 비교해 공통 베이스를 정한다.
 *
 * 무언가를 여기 추가하고 싶으면 그 전에 팀 합의가 필요하다.
 */

